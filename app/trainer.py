TITLE = ("{s} из {n}", "{n} ішінен {s}")


def _i(lang: str) -> int:
    return 1 if lang == "kk" else 0


def questions(lang: str) -> list[dict]:
    i = _i(lang)
    return [{"id": s["id"], "kind": KINDS[s["kind"]][i], "text": s["text"][i],
             "options": [{"id": o[0], "text": o[1 + i]} for o in s["options"]]} for s in SCENARIOS]


def check(qid: str, choice: str, lang: str) -> dict | None:
    s = BY_ID.get(qid)
    if not s or choice not in {o[0] for o in s["options"]}:
        return None
    return {"correct": choice == s["right"], "right": s["right"], "explain": s["explain"][_i(lang)]}


def score(answers: dict[str, str], lang: str) -> dict | None:
    """Результат прохождения. Нужны ответы на все ситуации, иначе результат не считается."""
    if set(answers) != set(BY_ID) or any(check(q, c, lang) is None for q, c in answers.items()):
        return None
    wrong = [s["id"] for s in SCENARIOS if answers[s["id"]] != s["right"]]
    n, k = len(SCENARIOS), len(SCENARIOS) - len(wrong)
    level = "all" if not wrong else "good" if k >= n - 2 else "weak"
    i = _i(lang)
    return {"score": k, "total": n, "wrong": wrong, "title": TITLE[i].format(s=k, n=n), "text": RESULT[level][i]}
